const { chromium } = require(process.env.PHASE5_PLAYWRIGHT || 'playwright-core')
const {resolve}=require('node:path')
const assert = require('node:assert/strict')
;(async()=>{
 const browser=await chromium.launch({executablePath:'/usr/bin/chromium',headless:true,args:['--no-sandbox']})
 try{
 const p=await browser.newPage({viewport:{width:1440,height:1000},reducedMotion:'reduce'})
 const errors=[]
 p.on('pageerror',e=>errors.push(e.message))
 const navigate=async (screen)=>{
   await p.goto('http://127.0.0.1:3987/phase5-fixture?screen='+screen,{timeout:45000})
   await p.getByText('Synthetic test data',{exact:true}).waitFor()
   await p.evaluate(()=>document.fonts.ready)
   await p.addStyleTag({content:'nextjs-portal { display: none !important; }'})
 }
 const shot=async name=>{
   const rendered=await p.locator('.brand img').evaluate(img=>img.naturalWidth>0)
   assert(rendered,'Supplied SVG rendered')
   assert(await p.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'No horizontal page overflow '+name)
   await p.screenshot({path:resolve(__dirname,'../../docs/phase5-screenshots',name+'.png'),fullPage:true,animations:'disabled'})
 }
 await navigate('welcome')
 await p.getByRole('heading',{name:/Take a breath/}).waitFor()
 assert(await p.evaluate(()=>Array.from(document.fonts).some(f=>f.family.includes('Syne') && f.status==='loaded')))
 for(let i=0;i<5 && !(await p.locator('.skip').evaluate(node=>node===document.activeElement));i++) await p.keyboard.press('Tab')
 assert(await p.locator('.skip').evaluate(node=>node===document.activeElement))
 await p.locator('.skip').evaluate(node=>node.blur())
 await shot('welcome')
 await navigate('dashboard')
 await p.getByRole('heading',{name:'Fresh',exact:true}).waitFor()
 await shot('dashboard')
 await p.getByRole('button',{name:'Off',exact:true}).click()
 await p.getByText('Off requested. Waiting for device telemetry.').waitFor()
 await navigate('fail')
 await p.getByRole('button',{name:'Freshen now',exact:true}).click()
 await p.getByText(/command could not be confirmed/).waitFor()
 await p.getByRole('button',{name:'Retry command'}).click()
 await p.getByText(/Freshen now requested/).waitFor()
 await navigate('override')
 await p.getByText(/Local CO₂ safety takes precedence/).waitFor()
 await navigate('calibrate')
 await p.getByRole('heading',{name:'Calibrate',exact:true}).waitFor()
 assert.equal(await p.locator('iframe').count(),0)
 await p.getByRole('checkbox').check()
 await p.getByRole('button',{name:'Start calibration',exact:true}).click()
 await p.getByText('34 of 60 seconds measured', {exact:false}).waitFor()
 await shot('calibration')
 await p.getByRole('button',{name:'Abort calibration'}).click()
 await p.getByRole('heading',{name:'Calibration aborted'}).waitFor()
 await navigate('details')
 await p.getByText('No matched forecast observations are available.').waitFor()
 await p.locator('.recharts-line').first().waitFor()
 await shot('details')
 await p.setViewportSize({width:820,height:1100})
 await navigate('dashboard')
 await p.getByRole('heading',{name:'Fresh',exact:true}).waitFor()
 await shot('tablet-dashboard')
 await p.setViewportSize({width:390,height:844})
 await navigate('dashboard')
 await p.getByRole('heading',{name:'Fresh',exact:true}).waitFor()
 await shot('mobile-dashboard')
 await navigate('stale')
 await p.getByRole('heading',{name:'Unavailable',exact:true}).waitFor()
 await p.getByText(/Last valid CO₂/).waitFor()
 assert.equal(await p.getByRole('heading',{name:'Fresh',exact:true}).count(),0)
 await shot('stale-device')
 await navigate('missing')
 await p.getByText('Waiting for device', {exact:true}).waitFor()
 await navigate('login')
 await p.getByRole('textbox',{name:'Email'}).fill('owner@example.invalid')
 await p.getByLabel('Password',{exact:true}).fill('synthetic')
 await p.getByRole('button',{name:'Sign in',exact:true}).click()
 await p.getByRole('alert').filter({hasText:'Sign-in failed'}).waitFor()
 await navigate('blocked')
 await p.getByRole('heading',{name:'Owner access required'}).waitFor()
 assert.deepEqual(errors,[])
 console.log('PASS Chromium desktop 1440, tablet 820 and mobile 390. Syne, SVG, keyboard, charts, missing/stale, auth, command pending/retry/override and calibration start/abort. Seven screenshots.')
 }finally{await browser.close()}
})().catch(error=>{console.error(error);process.exitCode=1})
